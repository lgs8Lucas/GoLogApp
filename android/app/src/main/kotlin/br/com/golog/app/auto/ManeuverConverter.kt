package br.com.golog.app.auto

import androidx.car.app.navigation.model.Maneuver as Car
import com.google.android.libraries.mapsplatform.turnbyturn.model.Maneuver as Nav

/**
 * Converte as manobras do turn-by-turn do Navigation SDK para os tipos do
 * Android Auto. Baseado no ManeuverConverter do exemplo do
 * google_navigation_flutter (Apache 2.0), com duas diferenças: TURN_SHARP_RIGHT
 * mapeia para curva fechada (o exemplo usava rampa) e manobras desconhecidas
 * viram TYPE_UNKNOWN em vez de lançar exceção — uma manobra nova do SDK não
 * pode derrubar a tela do carro.
 */
object ManeuverConverter {

    private val TYPES: Map<Int, Int> = mapOf(
        Nav.DEPART to Car.TYPE_DEPART,
        Nav.DESTINATION to Car.TYPE_DESTINATION,
        Nav.DESTINATION_LEFT to Car.TYPE_DESTINATION_LEFT,
        Nav.DESTINATION_RIGHT to Car.TYPE_DESTINATION_RIGHT,
        Nav.STRAIGHT to Car.TYPE_STRAIGHT,
        Nav.TURN_LEFT to Car.TYPE_TURN_NORMAL_LEFT,
        Nav.TURN_RIGHT to Car.TYPE_TURN_NORMAL_RIGHT,
        Nav.TURN_KEEP_LEFT to Car.TYPE_KEEP_LEFT,
        Nav.TURN_KEEP_RIGHT to Car.TYPE_KEEP_RIGHT,
        Nav.TURN_SLIGHT_LEFT to Car.TYPE_TURN_SLIGHT_LEFT,
        Nav.TURN_SLIGHT_RIGHT to Car.TYPE_TURN_SLIGHT_RIGHT,
        Nav.TURN_SHARP_LEFT to Car.TYPE_TURN_SHARP_LEFT,
        Nav.TURN_SHARP_RIGHT to Car.TYPE_TURN_SHARP_RIGHT,
        Nav.TURN_U_TURN_CLOCKWISE to Car.TYPE_U_TURN_RIGHT,
        Nav.TURN_U_TURN_COUNTERCLOCKWISE to Car.TYPE_U_TURN_LEFT,
        Nav.MERGE_UNSPECIFIED to Car.TYPE_MERGE_SIDE_UNSPECIFIED,
        Nav.MERGE_LEFT to Car.TYPE_MERGE_LEFT,
        Nav.MERGE_RIGHT to Car.TYPE_MERGE_RIGHT,
        Nav.FORK_LEFT to Car.TYPE_FORK_LEFT,
        Nav.FORK_RIGHT to Car.TYPE_FORK_RIGHT,
        Nav.ON_RAMP_UNSPECIFIED to Car.TYPE_ON_RAMP_NORMAL_RIGHT,
        Nav.ON_RAMP_LEFT to Car.TYPE_ON_RAMP_NORMAL_LEFT,
        Nav.ON_RAMP_RIGHT to Car.TYPE_ON_RAMP_NORMAL_RIGHT,
        Nav.ON_RAMP_KEEP_LEFT to Car.TYPE_ON_RAMP_NORMAL_LEFT,
        Nav.ON_RAMP_KEEP_RIGHT to Car.TYPE_ON_RAMP_NORMAL_RIGHT,
        Nav.ON_RAMP_SLIGHT_LEFT to Car.TYPE_ON_RAMP_SLIGHT_LEFT,
        Nav.ON_RAMP_SLIGHT_RIGHT to Car.TYPE_ON_RAMP_SLIGHT_RIGHT,
        Nav.ON_RAMP_SHARP_LEFT to Car.TYPE_ON_RAMP_SHARP_LEFT,
        Nav.ON_RAMP_SHARP_RIGHT to Car.TYPE_ON_RAMP_SHARP_RIGHT,
        Nav.ON_RAMP_U_TURN_CLOCKWISE to Car.TYPE_ON_RAMP_U_TURN_RIGHT,
        Nav.ON_RAMP_U_TURN_COUNTERCLOCKWISE to Car.TYPE_ON_RAMP_U_TURN_LEFT,
        Nav.OFF_RAMP_LEFT to Car.TYPE_OFF_RAMP_NORMAL_LEFT,
        Nav.OFF_RAMP_RIGHT to Car.TYPE_OFF_RAMP_NORMAL_RIGHT,
        Nav.OFF_RAMP_KEEP_LEFT to Car.TYPE_OFF_RAMP_SLIGHT_LEFT,
        Nav.OFF_RAMP_KEEP_RIGHT to Car.TYPE_OFF_RAMP_SLIGHT_RIGHT,
        Nav.OFF_RAMP_SLIGHT_LEFT to Car.TYPE_OFF_RAMP_SLIGHT_LEFT,
        Nav.OFF_RAMP_SLIGHT_RIGHT to Car.TYPE_OFF_RAMP_SLIGHT_RIGHT,
        Nav.OFF_RAMP_SHARP_LEFT to Car.TYPE_OFF_RAMP_NORMAL_LEFT,
        Nav.OFF_RAMP_SHARP_RIGHT to Car.TYPE_OFF_RAMP_NORMAL_RIGHT,
        Nav.ROUNDABOUT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW,
        Nav.ROUNDABOUT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW,
        Nav.ROUNDABOUT_STRAIGHT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_CW,
        Nav.ROUNDABOUT_STRAIGHT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_CCW,
        Nav.ROUNDABOUT_LEFT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW_WITH_ANGLE,
        Nav.ROUNDABOUT_LEFT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW_WITH_ANGLE,
        Nav.ROUNDABOUT_RIGHT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW_WITH_ANGLE,
        Nav.ROUNDABOUT_RIGHT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW_WITH_ANGLE,
        Nav.ROUNDABOUT_SLIGHT_LEFT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW_WITH_ANGLE,
        Nav.ROUNDABOUT_SLIGHT_LEFT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW_WITH_ANGLE,
        Nav.ROUNDABOUT_SLIGHT_RIGHT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW_WITH_ANGLE,
        Nav.ROUNDABOUT_SLIGHT_RIGHT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW_WITH_ANGLE,
        Nav.ROUNDABOUT_SHARP_LEFT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW_WITH_ANGLE,
        Nav.ROUNDABOUT_SHARP_LEFT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW_WITH_ANGLE,
        Nav.ROUNDABOUT_SHARP_RIGHT_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW_WITH_ANGLE,
        Nav.ROUNDABOUT_SHARP_RIGHT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW_WITH_ANGLE,
        Nav.ROUNDABOUT_U_TURN_CLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CW_WITH_ANGLE,
        Nav.ROUNDABOUT_U_TURN_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_ENTER_AND_EXIT_CCW_WITH_ANGLE,
        Nav.ROUNDABOUT_EXIT_CLOCKWISE to Car.TYPE_ROUNDABOUT_EXIT_CW,
        Nav.ROUNDABOUT_EXIT_COUNTERCLOCKWISE to Car.TYPE_ROUNDABOUT_EXIT_CCW,
        Nav.FERRY_BOAT to Car.TYPE_FERRY_BOAT,
        Nav.FERRY_TRAIN to Car.TYPE_FERRY_TRAIN,
        Nav.NAME_CHANGE to Car.TYPE_NAME_CHANGE,
    )

    fun toCarManeuverType(maneuver: Int): Int = TYPES[maneuver] ?: Car.TYPE_UNKNOWN

    /** Ângulo de saída da rotatória (1..360), exigido pelos tipos *_WITH_ANGLE. */
    fun roundaboutExitAngle(maneuver: Int): Int = when (maneuver) {
        Nav.ROUNDABOUT_SLIGHT_LEFT_CLOCKWISE,
        Nav.ROUNDABOUT_SLIGHT_RIGHT_CLOCKWISE,
        Nav.ROUNDABOUT_SLIGHT_LEFT_COUNTERCLOCKWISE,
        Nav.ROUNDABOUT_SLIGHT_RIGHT_COUNTERCLOCKWISE -> 10
        Nav.ROUNDABOUT_SHARP_LEFT_CLOCKWISE,
        Nav.ROUNDABOUT_SHARP_RIGHT_CLOCKWISE,
        Nav.ROUNDABOUT_SHARP_LEFT_COUNTERCLOCKWISE,
        Nav.ROUNDABOUT_SHARP_RIGHT_COUNTERCLOCKWISE -> 135
        Nav.ROUNDABOUT_U_TURN_CLOCKWISE,
        Nav.ROUNDABOUT_U_TURN_COUNTERCLOCKWISE -> 180
        else -> 45
    }
}
